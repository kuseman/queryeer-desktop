import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { delimiter, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const desktopRoot = resolve(scriptDir, "..");
const repoRoot = resolve(desktopRoot, "..");

const backendModule = "backend-plugin-devprobe";
const backendModuleRoot = resolve(repoRoot, "queryeer-backend", backendModule);
const backendClassesDir = resolve(backendModuleRoot, "target", "classes");

const pluginRoot = resolve(repoRoot, "plugins", "dev-classpath-probe");
const pluginClassesDir = resolve(pluginRoot, "classes");
const pluginDepsList = resolve(pluginRoot, "deps-list.txt");
const classpathRawFile = resolve(pluginRoot, ".deps-classpath.raw.txt");

function runMaven(args) {
  const result = process.platform === "win32"
    ? spawnSync("cmd.exe", ["/c", "mvnw.cmd", ...args], { cwd: repoRoot, stdio: "inherit" })
    : spawnSync(resolve(repoRoot, "mvnw"), args, { cwd: repoRoot, stdio: "inherit" });

  if (result.status !== 0) {
    throw new Error(`Maven command failed: ${args.join(" ")}`);
  }
}

function stageBackendClasses() {
  if (!existsSync(backendClassesDir)) {
    throw new Error(`Backend classes directory not found: ${backendClassesDir}`);
  }

  rmSync(pluginClassesDir, { recursive: true, force: true });
  mkdirSync(pluginClassesDir, { recursive: true });
  cpSync(backendClassesDir, pluginClassesDir, { recursive: true });
}

function stageDependencyList() {
  const raw = readFileSync(classpathRawFile, "utf8").trim();
  const entries = raw.length === 0
    ? []
    : raw
        .split(delimiter)
        .map((entry) => entry.trim())
        .filter(Boolean);

  writeFileSync(
    pluginDepsList,
    ["# Generated by queryeer-desktop/scripts/dev-classpath-probe-stage.mjs", ...entries].join("\n") + "\n",
    "utf8"
  );
}

function main() {
  runMaven(["-f", "queryeer-backend/pom.xml", "-pl", backendModule, "-am", "-DskipTests=true", "install"]);
  runMaven([
    "-f",
    `queryeer-backend/${backendModule}/pom.xml`,
    "-DskipTests=true",
    "dependency:build-classpath",
    `-Dmdep.outputFile=${classpathRawFile}`
  ]);

  stageBackendClasses();
  stageDependencyList();
  rmSync(classpathRawFile, { force: true });
  process.stdout.write(`Staged dev-classpath-probe artifacts to ${pluginRoot}\n`);
}

main();
