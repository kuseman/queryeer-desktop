import type { BackendGatewayStatus, RuntimePluginState } from "@queryeer/api/backend";
import type { ContributionKind } from "../../core/plugin-runtime/ContributionOwnership";
import type { FileEntity } from "@queryeer/api/files/FileEntity";
import type { RuntimeData } from "./runtime-data";

export type Severity = "error" | "warning" | "info";
export type Health = "ok" | "warning" | "error" | "inactive";

export type FrontendState = "active" | "warning" | "skipped" | "failed" | "not-loaded";

export type PluginRow = {
  id: string;
  name: string;
  version?: string;
  kind?: string;
  description?: string;
  modulePath?: string;
  dependencies: string[];
  requiredCapabilities: string[];
  providedCapabilities: string[];
  frontend?: { state: FrontendState; messages: string[]; activationIndex?: number; activationMs?: number };
  backend?: { state: RuntimePluginState; reason?: string };
  contributions: Contribution[];
  health: Health;
};

export type Contribution = {
  kind: ContributionKind;
  id: string;
  label: string;
  detail?: string;
  ownerId?: string;
};

export type AttentionItem = {
  severity: Severity;
  title: string;
  detail?: string;
  pluginId?: string;
  section: SectionId;
};

export type SectionId = "overview" | "plugins" | "contributions" | "engines" | "backend";

export const CONTRIBUTION_KIND_LABELS: Record<ContributionKind, string> = {
  command: "Commands",
  keybinding: "Keybindings",
  menuItem: "Menu items",
  filesystem: "Filesystems",
  editor: "Editors",
  view: "Sidebar views",
  panel: "Panels",
  statusItem: "Status bar items",
  toolbarAction: "Toolbar actions",
  welcome: "Welcome pages",
  settings: "Settings",
  queryEngine: "Query engines"
};

export type QueryEngineRegistration = { engineId: string; mimeTypes: string[] };

export type FileEngineMatch = {
  file: FileEntity;
  matchedEngineId?: string;
  matchedByResolver?: string;
};

/**
 * A file bound to one engine that would run on another (or on none). Binding is restricted to the engine owning the
 * file's MIME type and stale bindings are cleared, so this points to a bug such as resolvers in an unexpected order.
 */
export function hasEngineMismatch(match: FileEngineMatch): boolean {
  const bound = match.file.engineBinding?.engineId;
  return bound !== undefined && bound !== match.matchedEngineId;
}

/** Every contribution in the registry, with the plugin that registered it where known. */
export function collectContributions(runtime: RuntimeData, queryEngines: QueryEngineRegistration[] = []): Contribution[] {
  const { extensions, owners } = runtime;
  const result: Contribution[] = [];
  const add = (kind: ContributionKind, id: string, label: string | undefined, detail?: string) => {
    result.push({ kind, id, label: label || id, ...(detail ? { detail } : {}), ownerId: owners.ownerOf(kind, id) });
  };
  for (const command of extensions.commands) {
    add("command", command.id, command.category ? `${command.category}: ${command.title}` : command.title, command.enablement);
  }
  for (const binding of extensions.keybindings) {
    add("keybinding", binding.id, binding.key, binding.when ? `${binding.commandId} · when ${binding.when}` : binding.commandId);
  }
  for (const item of extensions.menu.items) {
    // Generated by a dynamic menu: not a registration of its own
    if ((item as { _generatedBy?: string })._generatedBy) {
      continue;
    }
    add("menuItem", item.id, item.label, item.commandId);
  }
  for (const filesystem of extensions.filesystems) {
    add("filesystem", filesystem.id, filesystem.title, filesystem.schemes.join(", "));
  }
  for (const editor of extensions.layout.editors) {
    add("editor", editor.id, editor.title, editor.supportedMimeTypes?.join(", "));
  }
  for (const view of extensions.layout.views) {
    add("view", view.id, view.title, view.defaultZone);
  }
  for (const panel of extensions.layout.panels) {
    add("panel", panel.id, panel.tabs.map((tab) => labelOf(tab) ?? tab.id).join(", "));
  }
  for (const item of extensions.layout.statusItems) {
    add("statusItem", item.id, undefined, item.commandId);
  }
  for (const action of extensions.layout.toolbarActions) {
    if ((action as { type?: string }).type === "separator") {
      continue;
    }
    add("toolbarAction", action.id, labelOf(action), (action as { commandId?: string }).commandId);
  }
  for (const welcome of extensions.layout.welcomes) {
    add("welcome", welcome.id, labelOf(welcome));
  }
  for (const settings of extensions.settings.contributions) {
    add("settings", settings.moduleId, settings.title, `${settings.settings.length} settings`);
  }
  for (const engine of queryEngines) {
    add("queryEngine", engine.engineId, engine.engineId, engine.mimeTypes.join(", ") || undefined);
  }
  return result;
}

function labelOf(value: object): string | undefined {
  const candidate = value as { title?: unknown; label?: unknown };
  if (typeof candidate.title === "string") {
    return candidate.title;
  }
  return typeof candidate.label === "string" ? candidate.label : undefined;
}

/**
 * One row per plugin id, merging the frontend manifest, its activation outcome, the backend runtime status and what
 * it contributes. External plugins share an id between frontend and backend, so they merge into one row.
 */
export function buildPluginRows(
  runtime: RuntimeData,
  backendStatus: BackendGatewayStatus | null,
  contributions: Contribution[]
): PluginRow[] {
  const { diagnostics } = runtime;
  const rows = new Map<string, PluginRow>();
  const rowFor = (id: string): PluginRow => {
    let row = rows.get(id);
    if (!row) {
      row = { id, name: id, dependencies: [], requiredCapabilities: [], providedCapabilities: [], contributions: [], health: "inactive" };
      rows.set(id, row);
    }
    return row;
  };

  for (const manifest of diagnostics.pluginManifests) {
    const row = rowFor(manifest.id);
    Object.assign(row, {
      name: manifest.name ?? manifest.id,
      version: manifest.version,
      kind: manifest.kind,
      description: manifest.description,
      modulePath: manifest.modulePath,
      dependencies: manifest.dependencies,
      requiredCapabilities: manifest.requiredCapabilities,
      providedCapabilities: manifest.providesCapabilities
    });
    row.frontend = { state: "not-loaded", messages: [] };
  }

  diagnostics.activationOrder.forEach((id, index) => {
    const row = rowFor(id);
    row.frontend = {
      state: "active",
      messages: [],
      activationIndex: index + 1,
      activationMs: diagnostics.activationDurations?.[id]
    };
  });

  for (const problem of diagnostics.pluginProblems ?? []) {
    const row = rowFor(problem.pluginId);
    const frontend = row.frontend ?? { state: "not-loaded", messages: [] };
    frontend.messages.push(problem.message);
    if (problem.state === "warning") {
      if (frontend.state === "active") {
        frontend.state = "warning";
      }
    } else {
      frontend.state = problem.state;
      frontend.activationMs ??= diagnostics.activationDurations?.[problem.pluginId];
    }
    row.frontend = frontend;
  }

  for (const error of diagnostics.externalLoadErrors ?? []) {
    const row = rowFor(error.pluginId);
    row.modulePath ??= error.modulePath;
    row.frontend = { state: "failed", messages: [...(row.frontend?.messages ?? []), `Failed to load module: ${error.message}`] };
  }

  for (const status of backendStatus?.runtimeStatus?.pluginStatuses ?? []) {
    const row = rowFor(status.pluginId);
    row.backend = { state: status.state, ...(status.reason ? { reason: status.reason } : {}) };
    // A plugin with a frontend keeps the frontend manifest's identity; relations are the union of both runtimes
    if (!row.frontend) {
      row.name = status.name ?? row.name;
      row.version ??= status.version;
    }
    row.dependencies = union(row.dependencies, [
      ...(status.dependencies ?? []),
      ...(status.optionalDependencies ?? []).map((id) => `${id} (optional)`)
    ]);
    row.requiredCapabilities = union(row.requiredCapabilities, status.requiredCapabilities ?? []);
    row.providedCapabilities = union(row.providedCapabilities, status.providesCapabilities ?? []);
  }

  for (const contribution of contributions) {
    if (contribution.ownerId) {
      rowFor(contribution.ownerId).contributions.push(contribution);
    }
  }

  for (const row of rows.values()) {
    row.health = healthOf(row);
  }
  return [...rows.values()].sort(comparePluginRows);
}

function union(first: string[], second: string[]): string[] {
  return second.length === 0 ? first : [...new Set([...first, ...second])];
}

/** Dependencies are described as `id` or `id (optional)`. */
export function dependencyId(dependency: string): string {
  return dependency.replace(/\s*\(optional\)$/, "");
}

function healthOf(row: PluginRow): Health {
  const frontend = row.frontend?.state;
  const backend = row.backend?.state;
  if (frontend === "failed" || backend === "failed") {
    return "error";
  }
  if (frontend === "skipped" || frontend === "warning" || backend === "skipped") {
    return "warning";
  }
  if (frontend === "active" || backend === "activated" || backend === "loaded") {
    return "ok";
  }
  return "inactive";
}

const HEALTH_RANK: Record<Health, number> = { error: 0, warning: 1, ok: 2, inactive: 3 };

/** Problems first, then by name. */
export function comparePluginRows(a: PluginRow, b: PluginRow): number {
  return HEALTH_RANK[a.health] - HEALTH_RANK[b.health] || a.name.localeCompare(b.name);
}

/** What needs a look, most severe first. */
export function collectAttention(
  runtime: RuntimeData,
  rows: PluginRow[],
  backendStatus: BackendGatewayStatus | null,
  fileMatches: FileEngineMatch[] = []
): AttentionItem[] {
  const items: AttentionItem[] = [];
  if (backendStatus?.state === "unavailable") {
    items.push({
      severity: "error",
      title: "Backend is unavailable",
      detail: backendStatus.error ?? "The backend process is not responding.",
      section: "backend"
    });
  }
  for (const row of rows) {
    if (row.frontend?.state === "failed" || row.frontend?.state === "skipped" || row.frontend?.state === "warning") {
      items.push({
        severity: row.frontend.state === "failed" ? "error" : "warning",
        title: `${row.name}: frontend ${row.frontend.state === "warning" ? "activated with warnings" : row.frontend.state}`,
        detail: row.frontend.messages.join("\n") || undefined,
        pluginId: row.id,
        section: "plugins"
      });
    }
    if (row.backend?.state === "failed" || row.backend?.state === "skipped") {
      items.push({
        severity: row.backend.state === "failed" ? "error" : "warning",
        title: `${row.name}: backend ${row.backend.state}`,
        detail: row.backend.reason,
        pluginId: row.id,
        section: "plugins"
      });
    }
  }
  for (const match of fileMatches.filter(hasEngineMismatch)) {
    items.push({
      severity: "warning",
      title: `${fileNameOf(match.file.uri)} would not run on its bound engine`,
      detail: `Bound to ${match.file.engineBinding?.engineId}, matched ${match.matchedEngineId ?? "no engine"}${match.matchedByResolver ? ` (by ${match.matchedByResolver})` : ""}`,
      section: "engines"
    });
  }
  const { invalidUserBindings, duplicateBindings } = runtime.keybindingDiagnostics;
  for (const binding of invalidUserBindings) {
    items.push({
      severity: "warning",
      title: `Keybinding ${binding.key} ignored`,
      detail: binding.reason === "unknown-command" ? `Unknown command ${binding.commandId}` : `Invalid key for ${binding.commandId}`,
      section: "contributions"
    });
  }
  if (duplicateBindings.length > 0) {
    items.push({
      severity: "info",
      title: `${duplicateBindings.length} keybinding conflict${duplicateBindings.length === 1 ? "" : "s"} resolved`,
      detail: duplicateBindings
        .slice(0, 5)
        .map((duplicate) => `${duplicate.key}: ${duplicate.winnerCommandId} shadows ${duplicate.shadowedCommandId}`)
        .join("\n"),
      section: "contributions"
    });
  }
  const rank: Record<Severity, number> = { error: 0, warning: 1, info: 2 };
  return items.sort((a, b) => rank[a.severity] - rank[b.severity]);
}

export function summarize(rows: PluginRow[]) {
  return {
    total: rows.length,
    frontendActive: rows.filter((row) => row.frontend?.state === "active" || row.frontend?.state === "warning").length,
    backendActive: rows.filter((row) => row.backend?.state === "activated" || row.backend?.state === "loaded").length,
    errors: rows.filter((row) => row.health === "error").length,
    warnings: rows.filter((row) => row.health === "warning").length
  };
}

/** Case-insensitive match of every whitespace-separated term against any of the fields. */
export function matchesQuery(query: string, ...fields: (string | undefined)[]): boolean {
  const terms = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  if (terms.length === 0) {
    return true;
  }
  const haystack = fields.filter(Boolean).join(" ").toLowerCase();
  return terms.every((term) => haystack.includes(term));
}

export function fileNameOf(uri: string): string {
  return uri.split(/[\\/]/).filter(Boolean).pop() ?? uri;
}

export function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(0)} KB`;
  if (bytes < 1024 * 1024 * 1024) return `${(bytes / (1024 * 1024)).toFixed(0)} MB`;
  return `${(bytes / (1024 * 1024 * 1024)).toFixed(1)} GB`;
}

export function formatDuration(ms: number): string {
  if (ms < 1) return "<1 ms";
  if (ms < 1000) return `${Math.round(ms)} ms`;
  if (ms < 60_000) return `${(ms / 1000).toFixed(ms < 10_000 ? 1 : 0)} s`;
  const minutes = Math.floor(ms / 60_000);
  if (minutes < 60) return `${minutes}m ${Math.floor((ms % 60_000) / 1000)}s`;
  const hours = Math.floor(minutes / 60);
  if (hours < 24) return `${hours}h ${minutes % 60}m`;
  return `${Math.floor(hours / 24)}d ${hours % 24}h`;
}

/** "12 s ago", or undefined when the timestamp is missing or unparseable. */
export function formatAgo(iso: string | undefined, now: number): string | undefined {
  if (!iso) return undefined;
  const time = Date.parse(iso);
  if (Number.isNaN(time)) return undefined;
  const elapsed = Math.max(0, now - time);
  return elapsed < 1000 ? "just now" : `${formatDuration(elapsed)} ago`;
}

export function formatClock(iso: string | undefined): string {
  if (!iso) return "-";
  const date = new Date(iso);
  return Number.isNaN(date.getTime()) ? iso : date.toLocaleTimeString();
}
